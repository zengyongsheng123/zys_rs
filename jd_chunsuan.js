function toWordArray(byteArray) {
    const words = [];

    for (let i = 0; i < byteArray.length; i++) {
        const wordIndex = i >>> 2;           // 计算字索引
        const shiftBits = 24 - (i % 4) * 8;  // 计算左移位数

        // 确保字存在
        if (!words[wordIndex]) {
            words[wordIndex] = 0;
        }

        // 合并字节到字中（确保是字节数据）
        words[wordIndex] |= (byteArray[i] & 0xFF) << shiftBits;
    }

    return {
        words: words,
        sigBytes: byteArray.length
    };
}
